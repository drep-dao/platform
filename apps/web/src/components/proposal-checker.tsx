/** Compact per-outcome counts for a list row (framework side) — kept visually distinct from coverage %. */
function OutcomeTally({ findings }: { findings: PcFinding[] }) {
  const m = new Map<string, number>();
  for (const f of findings ?? []) m.set(f.outcome, (m.get(f.outcome) ?? 0) + 1);
  if (!m.size) return null;
  return (
    <span className="flex max-w-[160px] flex-wrap items-center justify-end gap-1 sm:max-w-[240px]" title="Across all three dimensions (Template + Framework + Vision)">
      <span className="mr-0.5 text-[9px] uppercase tracking-wide text-neutral-400">all</span>
      {[...m.entries()].map(([o, n]) => (
        <span key={o} className={`rounded px-1.5 py-0.5 text-[10px] font-medium ${outcomeStyle(o)}`}>{n} {o}</span>
      ))}
    </span>
  );
}

