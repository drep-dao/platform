function scanStatusStyle(status: string): string {
  switch (status) {
    case 'DONE': return 'bg-emerald-100 text-emerald-700 dark:bg-emerald-950 dark:text-emerald-300';
    case 'PAID': return 'bg-sky-100 text-sky-700 dark:bg-sky-950 dark:text-sky-300';
    case 'FAILED_CONTACT_ADMIN': return 'bg-red-100 text-red-700 dark:bg-red-950 dark:text-red-300';
    case 'FAILED_RETRY': return 'bg-amber-100 text-amber-700 dark:bg-amber-950 dark:text-amber-300';
    default: return 'bg-neutral-100 text-neutral-500 dark:bg-neutral-800';
  }
}

// ── schedule (board) ──────────────────────────────────────────────────────────────
function ScheduleTab({ ai, onChange }: { ai: PcAiConfig | null; onChange: (c: PcAiConfig) => void }) {
  const t = useT();
  const [hours, setHours] = useState('24');
  const [autoOn, setAutoOn] = useState(false);
  const [busy, setBusy] = useState<string | null>(null);
  const [msg, setMsg] = useState<string | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [check, setCheck] = useState<PcCheckResult | null>(null);

  useEffect(() => { if (ai) { setHours(String(ai.checkIntervalHours)); setAutoOn(ai.autoCheckEnabled); } }, [ai]);

  const toggleAuto = async (on: boolean) => {
    setBusy('auto'); setErr(null); setMsg(null);
    try { const c = await api.updateAiConfig({ autoCheckEnabled: on }); onChange(c); setAutoOn(c.autoCheckEnabled); }
    catch (e) { setErr(e instanceof Error ? e.message : 'failed'); }
    finally { setBusy(null); }
  };

  const saveInterval = async () => {
    const n = Number(hours);
    if (!Number.isFinite(n) || n < 1) { setErr(t('Enter a number of hours (min 1).')); return; }
    setBusy('save'); setErr(null); setMsg(null);
    try { const c = await api.updateAiConfig({ checkIntervalHours: Math.round(n) }); onChange(c); setMsg(t('Saved.')); }
    catch (e) { setErr(e instanceof Error ? e.message : 'failed'); }
    finally { setBusy(null); }
  };
  const runNow = async () => {
    setBusy('run'); setErr(null); setMsg(null); setCheck(null);
    try { const r = await api.checkNow(); setCheck(r); api.aiConfig().then(onChange).catch(() => {}); }
    catch (e) { setErr(e instanceof Error ? e.message : 'failed'); }
    finally { setBusy(null); }
  };

  return (
    <div className="space-y-3">
      <h4 className="font-semibold">{t('Automatic check')}</h4>
      <p className="text-xs text-neutral-500">{t('The platform periodically looks for a new Treasury Withdrawal governance action and auto-generates its score, using the newest active template and no external links. Re-score with links in the Scores tab when needed.')}</p>
      {err ? <div className="text-sm text-red-600">{err}</div> : null}
      {msg ? <div className="text-sm text-emerald-600">{msg}</div> : null}
      <label className="flex items-center gap-2 text-sm">
        <input type="checkbox" checked={autoOn} onChange={(e) => toggleAuto(e.target.checked)} disabled={busy !== null} className="h-4 w-4" />
        <span className="font-medium">{t('Automatic review')}</span>
        <span className={`rounded px-1.5 py-0.5 text-[10px] font-semibold ${autoOn ? 'bg-emerald-100 text-emerald-700 dark:bg-emerald-950 dark:text-emerald-300' : 'bg-neutral-100 text-neutral-500 dark:bg-neutral-800'}`}>{autoOn ? t('ON') : t('OFF')}</span>
      </label>
      {!autoOn ? <p className="text-xs text-amber-600">{t('Automatic review is off — new proposals are not scored automatically. Use "Run check now" below, or score each one in the Scores tab.')}</p> : null}
      <div className="flex flex-wrap items-end gap-2">
        <label className="text-xs"><span className="mb-0.5 block text-neutral-500">{t('Check every (hours)')}</span>
          <input type="number" min={1} value={hours} onChange={(e) => setHours(e.target.value)} className="w-28 rounded-md border border-neutral-300 px-2 py-1 text-sm dark:border-neutral-700 dark:bg-neutral-900" /></label>
        <button onClick={saveInterval} disabled={busy !== null} className="rounded-md border border-emerald-500 px-2.5 py-1 text-xs text-emerald-700 hover:bg-emerald-50 disabled:opacity-40 dark:text-emerald-300 dark:hover:bg-emerald-950">{busy === 'save' ? t('Saving…') : t('Save')}</button>
      </div>
      <p className="text-xs text-neutral-400">{t('Last check')}: {ai?.lastCheckAt ? fmtDate(ai.lastCheckAt) : t('never')}</p>
      <div className="border-t border-neutral-200 pt-3 dark:border-neutral-800">
        <button onClick={runNow} disabled={busy !== null} className="rounded-md bg-emerald-600 px-4 py-1.5 text-sm font-semibold text-white hover:bg-emerald-700 disabled:opacity-50">{busy === 'run' ? t('Checking… (this can take a while)') : t('Run check now')}</button>
        {check ? (
          <div className="mt-2 text-xs">
            {!check.ran ? (
              <p className="text-neutral-500">{t('Not run')}{check.reason ? ` — ${check.reason}` : ''}.</p>
            ) : (
              <>
                <p className="text-emerald-600">{t('Scored')}: {check.scored.length}{check.reason ? ` (${check.reason})` : ''}</p>
                {check.errors.length ? <p className="text-amber-600">{t('Errors')}: {check.errors.length} — {check.errors[0]?.error}</p> : null}
              </>
            )}
          </div>
        ) : null}
      </div>
    </div>
  );
}

// ── scores management (board) ──────────────────────────────────────────────────────
function ScoresTab({ ai, templates }: { ai: PcAiConfig | null; templates: PcTemplate[] }) {
  const t = useT();
  const [actions, setActions] = useState<PcGovAction[] | null>(null);
  const [results, setResults] = useState<PcResult[] | null>(null);
  const [titles, setTitles] = useState<Record<string, { title: string | null; status: string }>>({});
  const [titlesLoading, setTitlesLoading] = useState(false);
  const [openId, setOpenId] = useState<string | null>(null);
  // Which proposals have a score request in flight — tracked here (not in the row) so it survives the
  // row being closed and reopened, and the list auto-refreshes when the request lands.
  const [scoring, setScoring] = useState<Set<string>>(new Set());
  const markScoring = useCallback((id: string, on: boolean) => setScoring((s) => { const n = new Set(s); if (on) n.add(id); else n.delete(id); return n; }), []);

  const loadResults = useCallback(() => { api.results().then(setResults).catch(() => setResults([])); }, []);
  useEffect(() => { api.govActions(150).then(setActions).catch(() => setActions([])); loadResults(); }, [loadResults]);

  // Resolve the proposal titles (so the list shows which withdrawal is which), cached server-side.
  useEffect(() => {
    if (!actions || !actions.length) return;
    setTitlesLoading(true);
    api.govActionTitles(actions.map((a) => a.proposalId))
      .then((m) => setTitles((prev) => ({ ...prev, ...m })))
      .catch(() => {})
      .finally(() => setTitlesLoading(false));
  }, [actions]);

  const latest = new Map<string, PcResult>();
  for (const r of results ?? []) if (!latest.has(r.govActionId)) latest.set(r.govActionId, r);
  const activeTemplate = templates[0]; // newest active (api.templates orders createdAt desc)

  return (
    <div className="space-y-3">
      <h4 className="font-semibold">{t('Treasury Withdrawals')}</h4>
      {!ai?.configured ? <p className="text-xs text-amber-600">{t('Configure an AI key (AI configuration tab) before scoring.')}</p> : null}
      {!activeTemplate ? <p className="text-xs text-amber-600">{t('Add a template (Templates tab) before scoring.')}</p> : null}
      {titlesLoading ? <p className="text-xs text-neutral-500">{t('Resolving proposal titles…')}</p> : null}
      {actions === null ? (
        <p className="text-sm text-neutral-500">{t('Loading…')}</p>
      ) : actions.length === 0 ? (
        <p className="text-sm text-neutral-500">{t('No Treasury Withdrawal actions found.')}</p>
      ) : (
        <ul className="divide-y divide-neutral-200 rounded-lg border border-neutral-200 dark:divide-neutral-800 dark:border-neutral-800">
          {actions.map((a) => {
            const res = latest.get(a.proposalId);
            const title = res?.govActionTitle || titles[a.proposalId]?.title || shortId(a.proposalId);
            return (
              <li key={a.proposalId} className="p-3 text-sm">
                <button onClick={() => setOpenId(openId === a.proposalId ? null : a.proposalId)} className="flex w-full items-center gap-3 text-left">
                  <ScoreIcon className="h-4 w-4 shrink-0 text-neutral-400" />
                  {res ? <ScorePair coverage={res.scorePct} framework={frameworkScore(res.questions)} vision={res.visionPct ?? frameworkScore(res.visionFindings ?? [])} /> : <span className="shrink-0 text-xs text-neutral-400">{t('not scored')}</span>}
                  <span className="min-w-0 flex-1 leading-tight">
                    <span className="flex flex-wrap items-center gap-2">
                      <span className="truncate font-medium">{title}</span>
                      <span className={`shrink-0 rounded px-1.5 py-0.5 text-[10px] font-medium capitalize ${statusStyle(a.status)}`}>{t(a.status)}</span>
                      {(() => { const tf = res?.templateFindings ?? []; const bt: 'middle' | 'large' | null = tf.some((f) => f.tier === 'large') ? 'large' : tf.some((f) => f.tier === 'middle') ? 'middle' : null; return bt ? <span className={`shrink-0 rounded px-1.5 py-0.5 text-[10px] font-semibold uppercase ${TIER_CHIP[bt]}`}>{bt}</span> : null; })()}
                      {scoring.has(a.proposalId) ? <span className="shrink-0 animate-pulse rounded bg-emerald-100 px-1.5 py-0.5 text-[10px] font-medium text-emerald-700 dark:bg-emerald-950 dark:text-emerald-300">{t('scoring…')}</span> : null}
                    </span>
                    {a.withdrawalAda != null ? <span className="mt-0.5 block text-sm font-semibold tabular-nums text-neutral-700 dark:text-neutral-200">{a.withdrawalAda.toLocaleString()} ₳ <span className="text-[11px] font-normal text-neutral-400">{t('requested')}</span></span> : null}
                    <span className="mt-0.5 block text-[11px] text-neutral-400">
                      {t('submitted')} {fmtTime(a.blockTime)}{res ? <> · {t('scored')} {fmtDate(res.createdAt)}</> : null}
                    </span>
                  </span>
                  <span className="flex shrink-0 items-center gap-2">
                    {res ? <OutcomeTally findings={[...(res.templateFindings ?? []), ...res.questions, ...(res.visionFindings ?? [])]} /> : null}
                    <span className="text-sm text-neutral-500 dark:text-neutral-400">{openId === a.proposalId ? '▲' : '▼'}</span>
                  </span>
                </button>
                {openId === a.proposalId ? (
                  <ScoreRow action={a} result={res} templateId={activeTemplate?.id} framework={ai?.framework ?? null} canScore={!!ai?.configured && !!activeTemplate} onChanged={loadResults} scoring={scoring.has(a.proposalId)} onScoring={markScoring} />
                ) : null}
              </li>
            );
          })}
        </ul>
      )}
    </div>
  );
}

function ScoreRow({ action, result, templateId, framework, canScore, onChanged, scoring, onScoring }: {
  action: PcGovAction; result?: PcResult; templateId?: string; framework?: PcReviewFramework | null; canScore: boolean; onChanged: () => void;
  scoring: boolean; onScoring: (id: string, on: boolean) => void;
}) {
  const t = useT();
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  const [fresh, setFresh] = useState<PcResult | null>(null);
  const [deleted, setDeleted] = useState(false);
  const [links, setLinks] = useState<string[]>([]);
  const [linkDraft, setLinkDraft] = useState('');

  const addLink = () => {
    const v = linkDraft.trim();
    if (!v) return;
    if (!/^https?:\/\//i.test(v)) { setErr(t('Enter a valid http(s) link.')); return; }
    if (links.length >= 10) { setErr(t('Up to 10 links.')); return; }
    setErr(null); setLinks((ls) => (ls.includes(v) ? ls : [...ls, v])); setLinkDraft('');
  };
  const run = async () => {
    if (!templateId) return;
    // Track the in-flight score at the PARENT (onScoring) too, so it survives this row being closed and
    // reopened: the request isn't bound to this component and keeps running, and a reopened row shows
    // "Scoring…" instead of an idle button you could click again (which would start a second score).
    setBusy(true); setErr(null); onScoring(action.proposalId, true);
    try { const r = await api.score(templateId, action.proposalId, links); setFresh(r); setDeleted(false); onChanged(); }
    catch (e) { setErr(e instanceof Error ? e.message : 'failed'); }
    finally { setBusy(false); onScoring(action.proposalId, false); }
  };
  const inProgress = busy || scoring;
  const del = async () => {
    const id = (fresh ?? result)?.id;
    if (!id) return;
    setBusy(true); setErr(null);
    try { await api.deleteResult(id); setFresh(null); setDeleted(true); onChanged(); }
    catch (e) { setErr(e instanceof Error ? e.message : 'failed'); }
    finally { setBusy(false); }
  };

  const shown = deleted ? null : (fresh ?? result ?? null);
  return (
    <div className="mt-2 space-y-2">
      {err ? <div className="text-sm text-red-600">{err}</div> : null}
      <div>
        <p className="text-xs text-neutral-500">{t('Optional external links (GitHub repos get a code-quality read). Re-scoring replaces the current score.')}</p>
        {links.length ? (
          <ul className="mt-1 space-y-1">
            {links.map((l) => (
              <li key={l} className="flex items-center gap-2 text-xs">
                {/github\.com/i.test(l) ? <span className="shrink-0 rounded bg-neutral-200 px-1 text-[10px] text-neutral-600 dark:bg-neutral-700 dark:text-neutral-300">GitHub</span> : null}
                <span className="truncate text-neutral-600 dark:text-neutral-300">{l}</span>
                <button type="button" onClick={() => setLinks((ls) => ls.filter((x) => x !== l))} className="shrink-0 text-red-600 hover:underline">{t('remove')}</button>
              </li>
            ))}
          </ul>
        ) : null}
        <div className="mt-1 flex gap-2">
          <input value={linkDraft} onChange={(e) => setLinkDraft(e.target.value)}
            onKeyDown={(e) => { if (e.key === 'Enter') { e.preventDefault(); addLink(); } }}
            placeholder="https://…" disabled={busy || links.length >= 10}
            className="flex-1 rounded-md border border-neutral-300 px-2 py-1 text-sm dark:border-neutral-700 dark:bg-neutral-900" />
          <button type="button" onClick={addLink} disabled={busy || !linkDraft.trim() || links.length >= 10}
            className="rounded-md border border-neutral-300 px-3 py-1 text-sm hover:bg-neutral-100 disabled:opacity-50 dark:border-neutral-700 dark:hover:bg-neutral-800">{t('Add link')}</button>
        </div>
      </div>
      <div className="flex gap-2">
        <button onClick={run} disabled={inProgress || !canScore}
          className="rounded-md bg-emerald-600 px-4 py-1.5 text-sm font-semibold text-white hover:bg-emerald-700 disabled:opacity-50">
          {inProgress ? t('Scoring… (this can take a moment)') : shown ? t('Re-score') : t('SCORE')}
        </button>
        {shown ? (
          <button onClick={del} disabled={inProgress}
            className="rounded-md border border-rose-300 px-3 py-1.5 text-sm text-rose-700 hover:bg-rose-50 disabled:opacity-40 dark:border-rose-900 dark:text-rose-300 dark:hover:bg-rose-950">
            {t('Delete score')}
          </button>
        ) : null}
      </div>
      {shown ? (
        <div className="space-y-2">
          <ResultCard r={shown} framework={framework} />
          {shown.prompt || shown.response ? <ScoreLog prompt={shown.prompt ?? null} response={shown.response ?? null} /> : <ResultLogLoader id={shown.id} />}
        </div>
      ) : null}
      <ProposalDetail proposalId={action.proposalId} />
    </div>
  );
}
