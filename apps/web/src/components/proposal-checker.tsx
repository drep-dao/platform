function OnePrompt({ ai, onChange, title, field, value, dflt, placeholders, required }: {
  ai: PcAiConfig | null; onChange: (c: PcAiConfig) => void; title: string;
  field: 'templatePrompt' | 'frameworkPrompt' | 'visionPrompt';
  value: string | undefined; dflt: string | undefined; placeholders: string[] | undefined; required: string[];
}) {
  const t = useT();
  const [prompt, setPrompt] = useState('');
  const [open, setOpen] = useState(false);
  const [busy, setBusy] = useState(false);
  const [msg, setMsg] = useState<string | null>(null);
  const [err, setErr] = useState<string | null>(null);
  useEffect(() => { if (value !== undefined) setPrompt((p) => (p === '' ? value : p)); }, [value]);
  const phs = placeholders ?? [];
  const used = (ph: string) => prompt.includes(ph);
  const missing = required.filter((ph) => !used(ph));
  const save = async () => {
    setBusy(true); setErr(null); setMsg(null);
    try { const c = await api.updateAiConfig({ [field]: prompt }); onChange(c); setMsg(t('Saved.')); }
    catch (e) { setErr(e instanceof Error ? e.message : 'failed'); }
    finally { setBusy(false); }
  };
  const reset = () => { if (dflt !== undefined) setPrompt(dflt); };
  return (
    <div className="rounded-md border border-neutral-200 dark:border-neutral-800">
      <div className="flex w-full items-center justify-between gap-2 px-3 py-2">
        <button onClick={() => setOpen((o) => !o)} className="flex-1 text-left text-sm font-semibold">{title}</button>
        <span className="flex items-center gap-2">
          <CopyButton getText={() => prompt || value || ''} />
          <button onClick={() => setOpen((o) => !o)} className="text-sm text-neutral-500 dark:text-neutral-400">{open ? '▼' : '▶'}</button>
        </span>
      </div>
      {open ? (
        <div className="space-y-2 border-t border-neutral-200 p-3 dark:border-neutral-800">
          <div className="flex flex-wrap gap-1.5">
            {phs.map((ph) => {
              const on = used(ph);
              const req = required.includes(ph);
              return (
                <button key={ph} type="button" onClick={() => setPrompt((p) => `${p}${p && !p.endsWith('\n') ? '\n' : ''}${ph}`)}
                  title={on ? t('used in the prompt') : req ? t('required — not used yet') : t('optional — not used')}
                  className={`rounded px-1.5 py-0.5 font-mono text-[11px] ${on ? 'bg-emerald-100 text-emerald-700 dark:bg-emerald-950 dark:text-emerald-300' : req ? 'bg-rose-100 text-rose-700 dark:bg-rose-950 dark:text-rose-300' : 'bg-neutral-100 text-neutral-500 dark:bg-neutral-800'}`}>
                  {on ? '✓' : req ? '✗' : '+'} {ph}
                </button>
              );
            })}
          </div>
          {err ? <div className="text-sm text-red-600">{err}</div> : null}
          {msg ? <div className="text-sm text-emerald-600">{msg}</div> : null}
          <textarea value={prompt} onChange={(e) => setPrompt(e.target.value)} rows={12}
            className="w-full rounded-md border border-neutral-300 px-2 py-1 font-mono text-xs dark:border-neutral-700 dark:bg-neutral-900" />
          {missing.length ? <p className="text-xs text-rose-600">{t('Add the required placeholder(s):')} {missing.join(', ')}</p> : null}
          <div className="flex gap-2">
            <button onClick={save} disabled={busy || missing.length > 0}
              className="rounded-md border border-emerald-500 px-2.5 py-1 text-xs text-emerald-700 hover:bg-emerald-50 disabled:opacity-40 dark:text-emerald-300 dark:hover:bg-emerald-950">
              {busy ? t('Saving…') : t('Save prompt')}
            </button>
            <button onClick={reset} disabled={busy}
              className="rounded-md border border-neutral-300 px-2.5 py-1 text-xs hover:bg-neutral-100 disabled:opacity-40 dark:border-neutral-700 dark:hover:bg-neutral-800">
              {t('Reset to default')}
            </button>
          </div>
        </div>
      ) : null}
    </div>
  );
}

