/** Per-area score 0–100 from findings: Supported=1, with condition=0.5, else 0, over applicable (excl. Not applicable). First-seen order. */
function areaScores(findings: PcFinding[]): { area: string; score: number; n: number }[] {
  const order: string[] = [];
  const agg = new Map<string, { w: number; n: number }>();
  for (const f of findings) {
    const l = (f.outcome || '').toLowerCase();
    if (l.includes('not applicable') || l.includes('n/a')) continue;
    if (!agg.has(f.area)) { agg.set(f.area, { w: 0, n: 0 }); order.push(f.area); }
    const a = agg.get(f.area)!;
    a.n += 1;
    a.w += l.includes('condition') ? 0.5 : l.includes('unsupported') || l.includes('unanswered') ? 0 : l.includes('supported') ? 1 : 0;
  }
  return order.map((area) => { const a = agg.get(area)!; return { area, score: a.n ? Math.round((a.w / a.n) * 100) : 0, n: a.n }; });
}

function radarHex(s: number) { return s >= 80 ? '#059669' : s >= 50 ? '#d97706' : '#e11d48'; }

/** Overall framework score 0–100 = mean of the 5 Triangle Forces area scores (max 500 → %). Null if no findings. */
export function frameworkScore(findings: PcFinding[]): number | null {
  const a = areaScores(findings);
  if (!a.length) return null;
  return Math.round(a.reduce((s, x) => s + x.score, 0) / a.length);
}

/** Evidence rate: of the answers where evidence was expected (evidenceCited yes|no), how many cite a source. */
function evidenceRate(findings: PcFinding[]): { pct: number; cited: number; asked: number } | null {
  let cited = 0, asked = 0;
  for (const f of findings) {
    const e = (f.evidenceCited || '').toLowerCase();
    if (e === 'yes') { cited += 1; asked += 1; }
    else if (e === 'no') { asked += 1; }
  }
  if (!asked) return null;
  return { pct: Math.round((cited / asked) * 100), cited, asked };
}

/** Inline SVG radar of the Triangle Forces areas — a visual profile of where a proposal is strong vs weak. */
function FrameworkRadar({ data }: { data: { area: string; score: number }[] }) {
  const N = data.length;
  if (N < 3) return null;
  const cx = 150, cy = 112, R = 72;
  const ang = (i: number) => -Math.PI / 2 + (i * 2 * Math.PI) / N;
  const clamp = (s: number) => Math.max(0, Math.min(100, s));
  const pt = (i: number, r: number) => `${(cx + r * Math.cos(ang(i))).toFixed(1)},${(cy + r * Math.sin(ang(i))).toFixed(1)}`;
  const ring = (f: number) => data.map((_, i) => pt(i, R * f)).join(' ');
  const poly = data.map((d, i) => pt(i, (R * clamp(d.score)) / 100)).join(' ');
  return (
    <svg viewBox="0 0 300 232" className="mx-auto w-full max-w-[360px]" role="img" aria-label="Triangle Forces radar">
      {[0.25, 0.5, 0.75, 1].map((f) => (
        <polygon key={f} points={ring(f)} fill="none" stroke="currentColor" strokeWidth="0.5" className="text-neutral-300 dark:text-neutral-700" />
      ))}
      {data.map((_, i) => (
        <line key={i} x1={cx} y1={cy} x2={cx + R * Math.cos(ang(i))} y2={cy + R * Math.sin(ang(i))} stroke="currentColor" strokeWidth="0.5" className="text-neutral-300 dark:text-neutral-700" />
      ))}
      <polygon points={poly} fill="rgb(16 185 129 / 0.18)" stroke="rgb(16 185 129)" strokeWidth="1.5" />
      {data.map((d, i) => {
        const a = ang(i);
        const lx = cx + (R + 13) * Math.cos(a);
        const ly = cy + (R + 13) * Math.sin(a);
        const anchor = Math.abs(Math.cos(a)) < 0.3 ? 'middle' : Math.cos(a) > 0 ? 'start' : 'end';
        const dx = (R * clamp(d.score)) / 100;
        return (
          <g key={i}>
            <circle cx={cx + dx * Math.cos(a)} cy={cy + dx * Math.sin(a)} r="3" fill={radarHex(d.score)} />
            <text x={lx} y={ly - 4} textAnchor={anchor} dominantBaseline="middle" fontSize="9.5" className="fill-neutral-500 dark:fill-neutral-400">{d.area}</text>
            <text x={lx} y={ly + 6} textAnchor={anchor} dominantBaseline="middle" fontSize="10" fontWeight="700" fill={radarHex(d.score)}>{d.score}%</text>
          </g>
        );
      })}
    </svg>
  );
}

// Group findings by area (first-seen order) + outcome tally — shared by the detail sections.
function groupByArea(findings: PcFinding[]): { area: string; items: PcFinding[] }[] {
  const areas: { area: string; items: PcFinding[] }[] = [];
  for (const f of findings) {
    let g = areas.find((a) => a.area === f.area);
    if (!g) { g = { area: f.area, items: [] }; areas.push(g); }
    g.items.push(f);
  }
  return areas;
}
function tallyOutcomes(items: PcFinding[]): [string, number][] {
  const m = new Map<string, number>();
  for (const f of items) m.set(f.outcome, (m.get(f.outcome) ?? 0) + 1);
  return [...m.entries()];
}

/** The findings detail for one scoring dimension: tally, evidence rate, optional radar, per-area list. */
/** Normalise a finding's evidence (legacy single string or an array of quotes) to a clean list. */
function toQuotes(v?: string | string[]): string[] {
  const raw = Array.isArray(v) ? v : v ? [v] : [];
  const clean = (s: string) => s.trim().replace(/^["“”''\s]+/, '').replace(/["“”''\s]+$/, '').trim();
  const seen = new Set<string>();
  const out: string[] = [];
  for (const item of raw) {
    const s = clean(String(item || ''));
    if (!s || seen.has(s.toLowerCase())) continue;
    seen.add(s.toLowerCase());
    out.push(s);
  }
  return out;
}

