const MAX_UPLOAD_BYTES = 8 * 1024 * 1024;
const fmtDate = (iso: string) => new Date(iso).toLocaleString();
const fmtTime = (unix: number) => (unix ? new Date(unix * 1000).toLocaleDateString() : '—');
const shortId = (id: string) => (id.length > 24 ? `${id.slice(0, 14)}…${id.slice(-6)}` : id);

export const scoreColor = (p: number) => (p >= 80 ? 'text-emerald-600 dark:text-emerald-400' : p >= 50 ? 'text-amber-600 dark:text-amber-400' : 'text-rose-600 dark:text-rose-400');
const scoreBar = (p: number) => (p >= 80 ? 'bg-emerald-500' : p >= 50 ? 'bg-amber-500' : 'bg-rose-500');

/** Colour for a framework outcome label (checked most-specific first; works for edited labels). */
const outcomeStyle = (label: string) => {
  const l = label.toLowerCase();
  if (l.includes('not applicable')) return 'bg-neutral-100 text-neutral-500 dark:bg-neutral-800 dark:text-neutral-400';
  if (l.includes('condition')) return 'bg-sky-100 text-sky-700 dark:bg-sky-950 dark:text-sky-300';
  if (l.includes('unsupported')) return 'bg-rose-100 text-rose-700 dark:bg-rose-950 dark:text-rose-300';
  if (l.includes('unanswered')) return 'bg-amber-100 text-amber-700 dark:bg-amber-950 dark:text-amber-300';
  if (l.includes('supported')) return 'bg-emerald-100 text-emerald-700 dark:bg-emerald-950 dark:text-emerald-300';
  return 'bg-neutral-100 text-neutral-500 dark:bg-neutral-800 dark:text-neutral-400';
};
const sourceLabel = (t: (s: string) => string, tpl: PcTemplate) =>
  tpl.source === 'LINK' ? t('link') : tpl.source === 'RULE_DOC' ? t('internal document') : tpl.fileName || t('upload');

/** Colour for an on-chain governance-action status badge. */
const statusStyle = (s: string) => {
  const l = (s || '').toLowerCase();
  if (l === 'active') return 'bg-emerald-100 text-emerald-700 dark:bg-emerald-950 dark:text-emerald-300';
  if (l === 'enacted' || l === 'ratified') return 'bg-sky-100 text-sky-700 dark:bg-sky-950 dark:text-sky-300';
  return 'bg-neutral-100 text-neutral-500 dark:bg-neutral-800 dark:text-neutral-400';
};

/** A small "copy to clipboard" button with brief confirmation. */
function CopyButton({ getText }: { getText: () => string | Promise<string> }) {
  const t = useT();
  const [copied, setCopied] = useState(false);
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(await getText());
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch { /* clipboard unavailable */ }
  };
  return (
    <button onClick={copy} className="rounded-md border border-neutral-300 px-2 py-0.5 text-xs hover:bg-neutral-100 dark:border-neutral-700 dark:hover:bg-neutral-800">
      {copied ? t('copied') : t('copy')}
    </button>
  );
}

/** Plain-text rendering of the framework for the clipboard. */
function frameworkToText(fw: PcReviewFramework): string {
  const outcomes = fw.outcomes.map((o) => `- ${o.label}: ${o.definition}`).join('\n');
  const areas = fw.areas
    .map((a) => `${a.title}${a.description ? ` — ${a.description}` : ''}\n${a.questions.map((q) => `${q.id}. ${q.text}`).join('\n')}`)
    .join('\n\n');
  return `${fw.title}\n\nReview outcomes:\n${outcomes}\n\nQuestions:\n${areas}${fw.attribution ? `\n\n${fw.attribution}` : ''}`;
}

/** Honest limits: the score is an automated reading of the proposal, not verification of its claims. */
