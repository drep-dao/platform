/** Public read-only view: the template + framework in use, and the scored Treasury Withdrawals.
 *  Scores are generated by the board in "Proposal Score Setup". */
export function ProposalChecker() {
  const t = useT();
  const [templates, setTemplates] = useState<PcTemplate[] | null>(null);
  const [results, setResults] = useState<PcResult[] | null>(null);
  const [actions, setActions] = useState<PcGovAction[] | null>(null);
  const [framework, setFramework] = useState<PcReviewFramework | null>(null);
  const [vision, setVision] = useState<PcVisionConfig | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    api.templates().then(setTemplates).catch((e) => setError(e instanceof Error ? e.message : 'failed'));
    api.results().then(setResults).catch(() => setResults([]));
    api.govActions(150).then(setActions).catch(() => setActions([])); // for submission-date ordering
    api.framework().then(setFramework).catch(() => setFramework(null));
    api.vision().then(setVision).catch(() => setVision(null));
  }, []);

  return (
    <div className="space-y-5">
      <div>
        <h2 className="text-lg font-semibold">{t('On-chain Proposal Score')}</h2>
        <p className="text-sm text-neutral-500">
          {t('Each Treasury Withdrawal governance action is scored against the Council template (Template coverage) and the review framework below. Scores are generated by the board; this page is read-only.')}
        </p>
      </div>
      <ScoreDisclaimer />
      {error ? <div className="text-sm text-red-600">{error}</div> : null}

      <TemplatePicker templates={templates} />
      <FrameworkView framework={framework} />
      <VisionView vision={vision} />
      <ScoredList results={results} actions={actions} templates={templates ?? []} framework={framework} />
    </div>
  );
}

