function AddTemplate({ onAdded }: { onAdded: () => void }) {
  const t = useT();
  const [mode, setMode] = useState<'upload' | 'link' | 'ruledoc'>('upload');
  const [title, setTitle] = useState('');
  const [url, setUrl] = useState('');
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  const [ruleDocs, setRuleDocs] = useState<RuleDocSummary[] | null>(null);
  const [ruleDocId, setRuleDocId] = useState('');

  useEffect(() => {
    if (mode === 'ruledoc' && ruleDocs === null) {
      ruleDocumentsApi.list('active').then(setRuleDocs).catch(() => ruleDocumentsApi.list().then(setRuleDocs).catch(() => setRuleDocs([])));
    }
  }, [mode, ruleDocs]);

  const onFile = async (file: File) => {
    setErr(null);
    if (file.size > MAX_UPLOAD_BYTES) { setErr(t('File too large (max 8 MB).')); return; }
    setBusy(true);
    try {
      const dataUrl = await new Promise<string>((resolve, reject) => {
        const r = new FileReader(); r.onload = () => resolve(String(r.result)); r.onerror = () => reject(new Error('read failed')); r.readAsDataURL(file);
      });
      await api.uploadTemplate({ title: title.trim() || file.name, dataUrl, fileName: file.name });
      setTitle(''); onAdded();
    } catch (e) { setErr(e instanceof Error ? e.message : 'failed'); }
    finally { setBusy(false); }
  };
  const addLink = async () => {
    setErr(null); setBusy(true);
    try { await api.linkTemplate({ title: title.trim() || undefined, url: url.trim() }); setTitle(''); setUrl(''); onAdded(); }
    catch (e) { setErr(e instanceof Error ? e.message : 'failed'); }
    finally { setBusy(false); }
  };
  const addRuleDoc = async () => {
    setErr(null); setBusy(true);
    try { await api.ruleDocTemplate({ ruleDocId, title: title.trim() || undefined }); setTitle(''); setRuleDocId(''); onAdded(); }
    catch (e) { setErr(e instanceof Error ? e.message : 'failed'); }
    finally { setBusy(false); }
  };

  const modes: { key: 'upload' | 'link' | 'ruledoc'; label: string }[] = [
    { key: 'upload', label: t('Upload file') },
    { key: 'link', label: t('From link') },
    { key: 'ruledoc', label: t('Internal document') },
  ];

  return (
    <div className="space-y-2 rounded-lg border border-dashed border-neutral-300 p-3 dark:border-neutral-700">
      <div className="flex flex-wrap gap-1 text-xs">
        {modes.map((m) => (
          <button key={m.key} onClick={() => setMode(m.key)} className={`rounded-md px-2 py-0.5 ${mode === m.key ? 'bg-emerald-600 text-white' : 'border border-neutral-300 dark:border-neutral-700'}`}>
            {m.label}
          </button>
        ))}
      </div>
      {err ? <div className="text-sm text-red-600">{err}</div> : null}
      <input value={title} onChange={(e) => setTitle(e.target.value)} placeholder={t('Template title (optional)')}
        className="w-80 max-w-full rounded-md border border-neutral-300 px-2 py-1 text-sm dark:border-neutral-700 dark:bg-neutral-900" />
      {mode === 'upload' ? (
        <div>
          <input type="file" accept=".pdf,.doc,.docx,.txt,.md,.markdown,.html,.htm,application/pdf,text/plain,text/markdown,text/html,application/vnd.openxmlformats-officedocument.wordprocessingml.document"
            disabled={busy} onChange={(e) => { const f = e.target.files?.[0]; if (f) void onFile(f); e.currentTarget.value = ''; }}
            className="block text-xs file:mr-2 file:rounded file:border-0 file:bg-emerald-600 file:px-2 file:py-1 file:text-white" />
          <p className="mt-1 text-[11px] text-neutral-400">{t('PDF, DOCX, TXT, Markdown or HTML — up to 8 MB.')}</p>
          {busy ? <p className="text-xs text-neutral-500">{t('Uploading + extracting text…')}</p> : null}
        </div>
      ) : mode === 'link' ? (
        <div className="flex flex-wrap items-center gap-2">
          <input value={url} onChange={(e) => setUrl(e.target.value)} placeholder="https://…"
            className="w-80 max-w-full rounded-md border border-neutral-300 px-2 py-1 font-mono text-xs dark:border-neutral-700 dark:bg-neutral-900" />
          <button onClick={addLink} disabled={busy || !url.trim()}
            className="rounded-md border border-emerald-500 px-2.5 py-1 text-xs text-emerald-700 hover:bg-emerald-50 disabled:opacity-40 dark:text-emerald-300 dark:hover:bg-emerald-950">
            {busy ? t('Fetching…') : t('Add')}
          </button>
        </div>
      ) : (
        <div className="flex flex-wrap items-center gap-2">
          {ruleDocs === null ? (
            <p className="text-xs text-neutral-500">{t('Loading…')}</p>
          ) : ruleDocs.length === 0 ? (
            <p className="text-xs text-neutral-500">{t('No rule documents available.')}</p>
          ) : (
            <select value={ruleDocId} onChange={(e) => setRuleDocId(e.target.value)}
              className="w-80 max-w-full rounded-md border border-neutral-300 px-2 py-1 text-sm dark:border-neutral-700 dark:bg-neutral-900">
              <option value="">{t('Select a rule document…')}</option>
              {ruleDocs.map((d) => <option key={d.id} value={d.id}>{d.title}{d.status !== 'ACTIVE' ? ` (${d.status.toLowerCase()})` : ''}</option>)}
            </select>
          )}
          <button onClick={addRuleDoc} disabled={busy || !ruleDocId}
            className="rounded-md border border-emerald-500 px-2.5 py-1 text-xs text-emerald-700 hover:bg-emerald-50 disabled:opacity-40 dark:text-emerald-300 dark:hover:bg-emerald-950">
            {busy ? t('Adding…') : t('Add')}
          </button>
        </div>
      )}
    </div>
  );
}

